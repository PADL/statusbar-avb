/// Standard AEM CONTROL descriptor `control_type` EUI-64 values
/// (IEEE 1722.1-2021 Clause 7.3.4, "Control Types").
///
/// Controls defined by the 1722.1 standard use the IEEE 1722-2011 OUI
/// (`90:e0:f0`) as the high 24 bits of the EUI-64. Vendor-defined
/// controls use a vendor-assigned EUI-64; the helpers here only name
/// the standard types.
///
/// The constants are grouped by function (general / audio / video /
/// media / radio / serial / network) using the two-byte sub-range
/// (bytes 3-4 of the EUI-64, called "category" below).

